_seen: set[str] = set()
_deduped: list[tuple] = []
for _item in FOREIGN_STOCKS:
    if _item[1] not in _seen:
        _seen.add(_item[1])
        _deduped.append(_item)
FOREIGN_STOCKS = _deduped


def search_foreign(query: str, limit: int = 10) -> list[dict]:
    query = query.strip().lower()
    results = [
        {"name": name, "ticker": ticker}
        for name, ticker in FOREIGN_STOCKS
        if query in name.lower() or query in ticker.lower()
    ]
    return results[:limit]
