US_TIER1_SET: set[str] = {c.ticker for c in US_POOL if c.tier == 1}


def get_pool(market: str) -> list[Candidate]:
    return KR_POOL if market == "KR" else US_POOL


def filter_pool(
    pool: list[Candidate],
    exclude_tags: list[str] | None = None,
    exclude_sectors: list[str] | None = None,
    exclude_tickers: list[str] | None = None,
    max_tier: int = 3,
) -> list[Candidate]:
    exc_tags = set(exclude_tags or [])
    exc_tickers = set(exclude_tickers or [])

    # exclude_sectors를 SECTOR_ALIASES로 확장 — "IT" → {"IT플랫폼", "IT", "테크", "IT서비스"}
    exc_sectors_expanded: set[str] = set()
    for s in (exclude_sectors or []):
        exc_sectors_expanded |= SECTOR_ALIASES.get(s, set()) | {s}

    return [
        c for c in pool
        if c.ticker not in exc_tickers
        and c.sector not in exc_sectors_expanded
        and not (exc_tags & set(c.tags))
        and c.tier <= max_tier
    ]


