def matches_sector(candidate: "Candidate", sector: str) -> bool:
    """
    후보가 주어진 업종에 속하는지 판단.
    sector 필드 직접 일치 OR SECTOR_ALIASES 확장 후 sector/tags 교집합.
    """
    expanded: set[str] = SECTOR_ALIASES.get(sector, set()) | {sector}
    return candidate.sector in expanded or bool(expanded & set(candidate.tags))
